class DrawingModuleTests(unittest.TestCase):
    def test_original_entry_points(self):
        for stem, names in EXPECTED.items():
            facade = importlib.import_module('svg_to_pptx.drawingml.' + stem)
            for name in names:
                with self.subTest(module=stem, name=name):
                    value = getattr(facade, name)
                    owner = importlib.import_module(value.__module__)
                    self.assertIs(value, getattr(owner, name))

    def test_modules_import_and_fit_limit(self):
        root = ROOT / '_engine' / 'svg_to_pptx' / 'drawingml'
        for path in sorted(root.glob('*.py'), reverse=True):
            with self.subTest(module=path.stem):
                self.assertLessEqual(len(path.read_text().splitlines()), 1000)
                importlib.import_module('svg_to_pptx.drawingml.' + path.stem)


if __name__ == '__main__':
    unittest.main()
