class NativeModuleBoundaryTests(unittest.TestCase):
    def test_original_facades_retain_callables(self) -> None:
        for name, symbols in EXPECTED.items():
            module = importlib.import_module(PREFIX + name)
            for symbol in symbols:
                with self.subTest(module=name, symbol=symbol):
                    self.assertTrue(callable(getattr(module, symbol)))

    def test_formula_crosses_all_parser_responsibilities(self) -> None:
        parser = importlib.import_module(PREFIX + "formula_parser")
        omml = importlib.import_module(PREFIX + "formula_omml")
        samples = [
            (r"\frac{x_1^2}{\sqrt{y}}", "f"),
            (r"\left(\sum_{i=1}^{n} i\right)", "d"),
            (r"\begin{matrix}a&b\\c&d\end{matrix}", "m"),
            (r"\ce{H2O}", "sSub"),
            (r"\newcommand{\sq}[1]{#1^2}\sq{x}", "sSup"),
            (r"\text{speed $v$}", "r"),
        ]
        for source, tag in samples:
            with self.subTest(source=source):
                expression = parser.parse_latex_formula(source, display=True)
                xml = omml.emit_omml(expression, display=True)
                root = ET.fromstring(xml)
                self.assertIsNotNone(root.find(".//{" + omml.MATH_NS + "}" + tag))
                self.assertEqual(omml.validate_omml_fragment(xml), xml)

    def test_formula_fail_closed_limits_survive_split(self) -> None:
        parser = importlib.import_module(PREFIX + "formula_parser")
        omml = importlib.import_module(PREFIX + "formula_omml")
        for source in (r"\unknown{x}", "{x", "x\x00", "{" * 140 + "x" + "}" * 140):
            with self.subTest(source=source[:25]):
                with self.assertRaises(parser.FormulaCompileError):
                    parser.parse_latex_formula(source, display=False)
        with self.assertRaises(parser.FormulaCompileError):
            omml.validate_omml_fragment('<!DOCTYPE x [<!ENTITY a "x">]><x>&a;</x>')

    def test_marker_context_is_shared_and_restored(self) -> None:
        facade = importlib.import_module(PREFIX + "marker_common")
        fallback = importlib.import_module(PREFIX + "marker_fallback")
        shared = importlib.import_module(PREFIX + "marker_common_shared")
        self.assertIs(facade.fallback_text_inheritance, fallback.fallback_text_inheritance)
        self.assertIs(facade._FALLBACK_TEXT_INHERITANCE, shared._FALLBACK_TEXT_INHERITANCE)
        initial = shared._FALLBACK_TEXT_INHERITANCE.get()
        with facade.fallback_text_inheritance({"fill": "#123456"}):
            self.assertEqual(shared._FALLBACK_TEXT_INHERITANCE.get(), {"fill": "#123456"})
            with fallback.fallback_text_inheritance({"text-anchor": "end"}):
                self.assertEqual(shared._FALLBACK_TEXT_INHERITANCE.get(), {"text-anchor": "end"})
            self.assertEqual(shared._FALLBACK_TEXT_INHERITANCE.get(), {"fill": "#123456"})
        self.assertIs(shared._FALLBACK_TEXT_INHERITANCE.get(), initial)


